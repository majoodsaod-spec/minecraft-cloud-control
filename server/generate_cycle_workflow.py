"""Generate bounded sequential Paper test jobs from max_cycles.

Usage: python server/generate_cycle_workflow.py
Commit the resulting YAML to GitHub before running the workflow.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "server/lifecycle_config.json"
DEST = ROOT / ".github/workflows/paper-state-test.yml"
MAX_CYCLES_LIMIT = 10


def build(count):
    if not isinstance(count, int) or not 1 <= count <= MAX_CYCLES_LIMIT:
        raise ValueError(f"max_cycles must be an integer from 1 to {MAX_CYCLES_LIMIT}")
    parts = ["""# GENERATED by server/generate_cycle_workflow.py
# Change server/lifecycle_config.json and regenerate before running.
name: Paper State Preservation Test

on:
  workflow_dispatch:

permissions:
  contents: read

concurrency:
  group: paper-lifecycle-test
  cancel-in-progress: false

jobs:
"""]
    for i in range(1, count + 1):
        block = f"""  cycle_{i}:
    name: cycle_{i}
"""
        if i > 1:
            block += f"    needs: cycle_{i-1}\n"
        block += """    runs-on: ubuntu-latest
    timeout-minutes: 10
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-java@v4
        with:
          distribution: temurin
          java-version: '25'
"""
        if i > 1:
            block += f"""      - name: Download previous state
        uses: actions/download-artifact@v4
        with:
          name: paper-state-cycle-{i-1}
          path: previous/
"""
        block += f"""      - name: Run cycle {i}
        run: python server/paper_lifecycle.py --cycle {i}
      - name: Upload cycle {i} snapshot
        uses: actions/upload-artifact@v4
        with:
          name: paper-state-cycle-{i}
          path: cycle-output/
          retention-days: {3 if i == count else 1}
          if-no-files-found: error
"""
        parts.append(block)
    return "\n".join(parts)


if __name__ == "__main__":
    data = json.loads(CONFIG.read_text(encoding="utf-8"))
    count = data["max_cycles"]
    DEST.parent.mkdir(parents=True, exist_ok=True)
    DEST.write_text(build(count), encoding="utf-8")
    print(f"Generated {count} sequential cycle jobs in {DEST}")
